import assert from 'node:assert/strict';
import {validate,validateLedger,totals,profit} from '../ledger.js';
const make=(kind,litres=0,extra={})=>({kind,litres,date:'2026-11-08',created:'2026-11-08T00:00:00Z',boat:'Boat 1',price:200,cash:0,...extra});
const opening=make('opening',100),sale=make('sale',20,{cash:4000}),credit=make('credit',15),donation=make('donation',5),repayment=make('repayment',10,{cash:2000});
const records=[opening,sale,credit,donation,repayment];validateLedger(records);
assert.equal(totals(records).stock,60);assert.equal(totals(records).debt['Boat 1'],5);assert.equal(totals(records).cash,6000);
assert.throws(()=>validateLedger([opening,make('sale',101)]),/Insufficient/);
assert.throws(()=>validateLedger([opening,credit,make('repayment',16)]),/exceeds/);
assert.throws(()=>validateLedger([make('sale',1),{...opening,date:'2026-11-09'}]),/Insufficient/);
assert.throws(()=>validateLedger([{...opening,void:true},sale]),/Insufficient/);
assert.equal(totals([{...sale,void:true},opening]).stock,100);
assert.throws(()=>validate(make('sale',-1)),/non-negative/);
assert.throws(()=>validate(make('purchase',NaN)),/non-negative/);
assert.throws(()=>validate(make('credit',1,{boat:'Boat 90'})),/Choose a boat/);
assert.throws(()=>validate(make('opening',1,{date:'2026-02-30'})),/valid date/);
const boat={kind:'boat',date:'2026-11-08',created:'',boat:'Boat 1',income:7000,rent:50,uganda:0,fuelLitres:8,fuelCash:1600,gowi:0,charging:140,amali:2400,boss:1580,expenses:0,commission:158};
validate(boat);assert.equal(profit(boat).net,1422);assert.throws(()=>validateLedger([boat,boat]),/already exists/);
assert.equal(totals([boat]).income,7000);assert.equal(totals([boat]).stock,0);
console.log('Passed: stock, debts, repayments, voids, chronology, dates, numeric validation, duplicate daily records and source profit calculation.');
